    def detect_death_day(self, journey_data):
        """Detect the day when death likely occurred based on static values"""
        if len(journey_data) < 10:  # Need sufficient data points
            return None
            
        # Look for patterns indicating death (static values for extended periods)
        for start_idx in range(5, len(journey_data) - 5):  # Start checking after day 5
            current_row = journey_data.iloc[start_idx]
            
            # Check if the next 5+ days have identical values (indicating death/simulation stop)
            static_count = 0
            for check_idx in range(start_idx, min(start_idx + 10, len(journey_data))):
                check_row = journey_data.iloc[check_idx]
                
                # Check if key values are identical (indicating simulation stopped)
                if (abs(check_row['primary_bacteria_level'] - current_row['primary_bacteria_level']) < 0.001 and
                    abs(check_row['immunity_level'] - current_row['immunity_level']) < 0.001 and
                    abs(check_row['toxicity_level'] - current_row['toxicity_level']) < 0.001 and
                    check_row['sepsis'] == current_row['sepsis'] and
                    check_row['is_treated'] == current_row['is_treated']):
                    static_count += 1
                else:
                    break
            
            # If we found 5+ consecutive identical days, death likely occurred
            if static_count >= 5:
                return current_row['day_of_journey']
        
        return None
    
    def determine_death_cause(self, death_row):
        """Determine the likely cause of death based on final state"""
        causes = []
        
        # High toxicity death
        if death_row['toxicity_level'] > 3.5:
            causes.append("Toxicity")
        
        # Sepsis death
        if death_row['sepsis']:
            causes.append("Sepsis")
        
        # Severe infection death
        if death_row['primary_bacteria_level'] > 3.0:
            causes.append("Severe infection")
        
        # Default if no clear cause identified
        if not causes:
            causes.append("Multi-organ failure")
        
        return " + ".join(causes)
    
    def _parse_drug_and_resistance_data(self, journey_data):
        """Parse drug levels and resistance data from journey data"""
        drug_data = {
            'has_drugs': False,
            'drug_levels': {},
            'activity_r': {}
        }
        
        # Check if there are any drugs in this journey
        has_treatment = journey_data['current_drugs'].notna() & (journey_data['current_drugs'] != "")
        if not has_treatment.any():
            return drug_data
        
        drug_data['has_drugs'] = True
        
        # Parse current_drugs field to extract drug names and levels
        for _, row in journey_data.iterrows():
            if pd.isna(row['current_drugs']) or row['current_drugs'] == "":
                continue
                
            # Parse drug string format: "drug1:level1;drug2:level2"
            drugs_str = row['current_drugs']
            if drugs_str and isinstance(drugs_str, str):
                for drug_entry in drugs_str.split(';'):
                    if ':' in drug_entry:
                        drug_name, level_str = drug_entry.split(':', 1)
                        drug_name = drug_name.strip()
                        try:
                            level = float(level_str.strip())
                            if drug_name not in drug_data['drug_levels']:
                                drug_data['drug_levels'][drug_name] = pd.Series(index=journey_data.index, dtype=float)
                            drug_data['drug_levels'][drug_name].loc[row.name] = level
                        except ValueError:
                            continue
        
        # Parse resistance_activity_r field  
        for _, row in journey_data.iterrows():
            if pd.isna(row['resistance_activity_r']) or row['resistance_activity_r'] == "":
                continue
                
            # Parse resistance string format: "drug1:value1;drug2:value2"
            resistance_str = row['resistance_activity_r']
            if resistance_str and isinstance(resistance_str, str):
                for resistance_entry in resistance_str.split(';'):
                    if ':' in resistance_entry:
                        drug_name, value_str = resistance_entry.split(':', 1)
                        drug_name = drug_name.strip()
                        try:
                            value = float(value_str.strip())
                            if drug_name not in drug_data['activity_r']:
                                drug_data['activity_r'][drug_name] = pd.Series(index=journey_data.index, dtype=float)
                            drug_data['activity_r'][drug_name].loc[row.name] = value
                        except ValueError:
                            continue
        
        return drug_data
    
    def _determine_actual_resolution(self, journey_data):
        """Determine the actual resolution based on the data"""
        final_resolution = journey_data['resolution_type'].iloc[-1]
        
        # If resolution is NaN or empty, it's an ongoing journey
        if pd.isna(final_resolution) or final_resolution == '':
            return 'Ongoing'
        
        # Otherwise use the resolution from the data
        return final_resolution
    
