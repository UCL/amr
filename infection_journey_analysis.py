    def calculate_30_day_mortality(self):
        """Calculate and visualize 30-day mortality probability."""
        if self.verbose:
            print("\nCalculating 30-day mortality analysis...")
        
        # Filter journeys that either died within 30 days or survived at least 30 days
        mortality_analysis = []
        
        for journey_id in self.journey_summary['journey_id'].unique():
            journey_info = self.journey_summary[self.journey_summary['journey_id'] == journey_id].iloc[0]
            
            # Include if journey lasted at least 30 days OR ended in death
            if journey_info['duration_days'] >= 30 or journey_info['died']:
                mortality_analysis.append({
                    'journey_id': journey_id,
                    'died_within_30_days': journey_info['died_within_30_days'],
                    'duration_days': min(journey_info['duration_days'], 30),
                    'age_at_onset': journey_info['age_at_onset'],
                    'sex': journey_info['sex'],
                    'primary_bacteria': journey_info['primary_bacteria'],
                    'developed_sepsis': journey_info['developed_sepsis'],
                    'was_treated': journey_info['was_treated']
                })
        
        mortality_df = pd.DataFrame(mortality_analysis)
        
        if len(mortality_df) == 0:
            if self.verbose:
                print("No journeys available for 30-day mortality analysis.")
            return None
        
        # Calculate overall 30-day mortality rate
        overall_mortality = mortality_df['died_within_30_days'].mean()
        if self.verbose:
            print(f"Overall 30-day mortality rate: {overall_mortality:.1%} ({mortality_df['died_within_30_days'].sum()}/{len(mortality_df)} cases)")
        
        # Create mortality analysis plots
        fig, ((ax1, ax2), (ax3, ax4)) = plt.subplots(2, 2, figsize=(15, 10))
        fig.suptitle('30-Day Mortality Analysis', fontsize=14, fontweight='bold')
        
        # Mortality by bacteria type
        bacteria_mortality = mortality_df.groupby('primary_bacteria')['died_within_30_days'].agg(['count', 'sum', 'mean']).reset_index()
        bacteria_mortality = bacteria_mortality[bacteria_mortality['count'] >= 5]  # At least 5 cases
        bacteria_mortality = bacteria_mortality.sort_values('mean', ascending=True)
        
        if len(bacteria_mortality) > 0:
            ax1.barh(range(len(bacteria_mortality)), bacteria_mortality['mean'], color='crimson', alpha=0.7)
            ax1.set_yticks(range(len(bacteria_mortality)))
            ax1.set_yticklabels([name.replace('_', ' ').title() for name in bacteria_mortality['primary_bacteria']])
            ax1.set_xlabel('30-Day Mortality Rate')
            ax1.set_title('Mortality by Bacteria Type')
            ax1.grid(True, alpha=0.3, axis='x')
        
        # Mortality by sepsis development
        sepsis_mortality = mortality_df.groupby('developed_sepsis')['died_within_30_days'].mean()
        ax2.bar(['No Sepsis', 'Developed Sepsis'], sepsis_mortality.values, color=['lightblue', 'darkred'], alpha=0.7)
        ax2.set_ylabel('30-Day Mortality Rate')
        ax2.set_title('Mortality by Sepsis Development')
        ax2.grid(True, alpha=0.3, axis='y')
        
        # Mortality by treatment status
        treatment_mortality = mortality_df.groupby('was_treated')['died_within_30_days'].mean()
        ax3.bar(['Not Treated', 'Treated'], treatment_mortality.values, color=['orange', 'green'], alpha=0.7)
        ax3.set_ylabel('30-Day Mortality Rate')
        ax3.set_title('Mortality by Treatment Status')
        ax3.grid(True, alpha=0.3, axis='y')
        
        # Age distribution of deaths vs survivors
        died_ages = mortality_df[mortality_df['died_within_30_days']]['age_at_onset'] / 365.25
        survived_ages = mortality_df[~mortality_df['died_within_30_days']]['age_at_onset'] / 365.25
        
        ax4.hist([died_ages, survived_ages], bins=20, alpha=0.7, label=['Died', 'Survived'], color=['red', 'blue'])
        ax4.set_xlabel('Age at Onset (years)')
        ax4.set_ylabel('Frequency')
        ax4.set_title('Age Distribution: Deaths vs Survivors')
