    def process_data(self):
        """Process and clean the loaded data."""
        # Convert boolean columns
        bool_cols = ['sepsis', 'hospital_acquired', 'infection_identified', 'resistance_testing_done']
        for col in bool_cols:
            self.df[col] = self.df[col].astype(bool)
            
        # Create treatment status
        self.df['is_treated'] = self.df['current_drugs'].notna() & (self.df['current_drugs'] != "")
        
        # Create infection state categories
        self.df['infection_state'] = 'Unknown'
        self.df.loc[self.df['sepsis'] == True, 'infection_state'] = 'Sepsis'
        self.df.loc[(self.df['sepsis'] == False) & (self.df['is_treated'] == True), 'infection_state'] = 'Treated'
        self.df.loc[(self.df['sepsis'] == False) & (self.df['is_treated'] == False), 'infection_state'] = 'Not Treated'
        
        # Syndrome mapping (syndromes 1-10)
        self.syndrome_names = {
            1: "Bloodstream infection",
            2: "Pneumonia", 
            3: "Urinary tract infection",
            4: "Skin/soft tissue infection",
            5: "Intra-abdominal infection",
            6: "Central nervous system infection",
            7: "Bone/joint infection",
            8: "Endocarditis", 
            9: "Surgical site infection",
            10: "Other/unspecified infection"
        }
        
        # Process resolution types
        self.df['resolution_type'] = self.df['resolution_type'].fillna('Ongoing')
        
        # Create journey summaries
        self.journey_summary = self._create_journey_summary()
        
    def parse_drug_data(self, drug_string):
        """Parse drug data string into list of (drug_name, level) tuples."""
        if pd.isna(drug_string) or drug_string == "":
            return []
        
        drugs = []
        for item in drug_string.split(";"):
            if ":" in item:
                drug_name, level = item.split(":")
                drugs.append((drug_name.strip(), float(level)))
        return drugs
    
    def _create_journey_summary(self):
        """Create summary statistics for each journey."""
        summary_stats = []
        
        for journey_id in self.df['journey_id'].unique():
            journey_data = self.df[self.df['journey_id'] == journey_id].copy()
            journey_data = journey_data.sort_values('day_of_journey')
            
            summary = {
                'journey_id': journey_id,
                'individual_id': journey_data['individual_id'].iloc[0],
                'age_at_onset': journey_data['age_at_onset'].iloc[0],
                'sex': journey_data['sex'].iloc[0],
                'region': journey_data['region_living'].iloc[0],
                'primary_bacteria': journey_data['primary_bacteria'].iloc[0],
                'syndrome': journey_data['syndrome'].iloc[0],
                'immunodeficiency': journey_data['immunodeficiency'].iloc[0],
                'hospital_acquired': journey_data['hospital_acquired'].iloc[0],
                'duration_days': journey_data['day_of_journey'].max(),
                'max_bacteria_level': journey_data['primary_bacteria_level'].max(),
                'developed_sepsis': journey_data['sepsis'].any(),
                'was_treated': journey_data['is_treated'].any(),
                'treatment_failures': journey_data['treatment_failures'].max(),
                'resolution_type': self._determine_actual_resolution(journey_data),
                'died': self._determine_actual_resolution(journey_data) == 'Death',
                'died_within_30_days': (self._determine_actual_resolution(journey_data) == 'Death') and (journey_data['day_of_journey'].max() <= 30),
                'drug_selection_occurred': journey_data['drug_selection_bacteria'].notna().any(),
                'selected_drug': journey_data['selected_drug'].dropna().iloc[0] if journey_data['selected_drug'].notna().any() else None
            }
            summary_stats.append(summary)
            
        return pd.DataFrame(summary_stats)
    
