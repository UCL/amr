    def detect_death_day(self, journey_data):
        """Detect the day when death likely occurred based on static values"""
        if len(journey_data) < 10:  # Need sufficient data points
            return None
            
        # Look for patterns indicating death (static values for extended periods)
        for start_idx in range(5, len(journey_data) - 5):  # Start checking after day 5
            current_row = journey_data.iloc[start_idx]
            
            # Check if the next 5+ days have identical values (indicating death/simulation stop)
            static_count = 0
            for check_idx in range(start_idx, min(start_idx + 10, len(journey_data))):
                check_row = journey_data.iloc[check_idx]
                
                # Check if key values are identical (indicating simulation stopped)
                if (
                            abs(check_row['primary_bacteria_level'] - current_row['primary_bacteria_level']) < 0.001
                            and abs(check_row['clearance_hazard'] - current_row['clearance_hazard']) < 0.001
                            and abs(check_row['toxicity_level'] - current_row['toxicity_level']) < 0.001
                            and check_row['sepsis'] == current_row['sepsis']
                            and check_row['is_treated'] == current_row['is_treated']
                        ):
                            static_count += 1
                else:
                            break
            
            # If we found 5+ consecutive identical days, death likely occurred
            if static_count >= 5:
                return current_row['day_of_journey']
        
        return None
    
    def determine_death_cause(self, death_row):
        """Determine the likely cause of death based on final state"""
        causes = []
        
        # High toxicity death
        if death_row['toxicity_level'] > 3.5:
            causes.append("Toxicity")
        
        # Sepsis death
        if death_row['sepsis']:
            causes.append("Sepsis")
        
        # Severe infection death
        if death_row['primary_bacteria_level'] > 3.0:
            causes.append("Severe infection")
        
        # Default if no clear cause identified
        if not causes:
            causes.append("Multi-organ failure")
        
        return " + ".join(causes)
    
    def _parse_drug_and_resistance_data(self, journey_data):
        """Parse drug levels and resistance data from journey data"""
        drug_data = {
            'has_drugs': False,
            'drug_levels': {},
            'activity_r': {},
            'infection_resistance_any': {},
            'infection_resistance_majority': {},
        }
        
        # Check if there are any drugs in this journey
        has_treatment = journey_data['current_drugs'].notna() & (journey_data['current_drugs'] != "")
        if not has_treatment.any():
            return drug_data
        
        drug_data['has_drugs'] = True
        
        # Parse current_drugs field to extract drug names and levels
        for _, row in journey_data.iterrows():
            if pd.isna(row['current_drugs']) or row['current_drugs'] == "":
                continue
                
            # Parse drug string format: "drug1:level1;drug2:level2"
            drugs_str = row['current_drugs']
            if drugs_str and isinstance(drugs_str, str):
                for drug_entry in drugs_str.split(';'):
                    if ':' in drug_entry:
                        drug_name, level_str = drug_entry.split(':', 1)
                        drug_name = drug_name.strip()
                        try:
                            level = float(level_str.strip())
                            if drug_name not in drug_data['drug_levels']:
                                drug_data['drug_levels'][drug_name] = pd.Series(index=journey_data.index, dtype=float)
                            drug_data['drug_levels'][drug_name].loc[row.name] = level
                        except ValueError:
                            continue
        
        # Parse resistance_activity_r field  
        for _, row in journey_data.iterrows():
            if pd.isna(row['resistance_activity_r']) or row['resistance_activity_r'] == "":
                continue
                
            # Parse resistance string format: "drug1:value1;drug2:value2"
            resistance_str = row['resistance_activity_r']
            if resistance_str and isinstance(resistance_str, str):
                for resistance_entry in resistance_str.split(';'):
                    if ':' in resistance_entry:
                        drug_name, value_str = resistance_entry.split(':', 1)
                        drug_name = drug_name.strip()
                        try:
                            value = float(value_str.strip())
                            if drug_name not in drug_data['activity_r']:
                                drug_data['activity_r'][drug_name] = pd.Series(index=journey_data.index, dtype=float)
                            drug_data['activity_r'][drug_name].loc[row.name] = value
                        except ValueError:
                            continue

        drug_data['infection_resistance_any'] = self._parse_per_drug_float_series(
            journey_data,
            ['resistances_any_r', 'resistance_any_r']
        )
        drug_data['infection_resistance_majority'] = self._parse_per_drug_float_series(
            journey_data,
            ['resistances_majority_r', 'resistance_majority_r']
        )
        
        return drug_data

    def _parse_per_drug_float_series(self, journey_data, column_candidates):
        """Parse semicolon-delimited key:value strings into per-drug float series."""
        if isinstance(column_candidates, str):
            column_candidates = [column_candidates]

        per_drug_series = {}
        for column in column_candidates:
            if column not in journey_data.columns:
                continue

            column_values = journey_data[column]
            for row_index, cell in column_values.items():
                if pd.isna(cell) or str(cell).strip() == "":
                    continue

                for entry in str(cell).split(';'):
                    if ':' not in entry:
                        continue
                    drug_name, value_str = entry.split(':', 1)
                    drug_name = drug_name.strip()
                    try:
                        numeric_value = float(value_str.strip())
                    except ValueError:
                        continue

                    if drug_name not in per_drug_series:
                        per_drug_series[drug_name] = pd.Series(
                            data=np.nan,
                            index=journey_data.index,
                            dtype=float,
                        )
                    per_drug_series[drug_name].loc[row_index] = numeric_value

        return per_drug_series

    def _extract_resistance_series(self, journey_data, column_candidates):
        """
        Return a tuple of (series, source_column) for resistance values parsed from the
        provided candidate columns. source_column is None when no column is present.
        """
        if isinstance(column_candidates, str):
            column_candidates = [column_candidates]

        for column in column_candidates:
            if column in journey_data.columns:
                values = [self._max_value_from_key_string(cell) for cell in journey_data[column]]
                series = pd.Series(values, index=journey_data.index, dtype=float)
                return series, column

        empty_series = pd.Series([np.nan] * len(journey_data), index=journey_data.index, dtype=float)
        return empty_series, None

    def _max_value_from_key_string(self, cell):
        """Parse semicolon-delimited key:value strings and return max numeric value."""
        if pd.isna(cell) or str(cell).strip() == "":
            return np.nan

        max_val = 0.0
        found_numeric = False
        for entry in str(cell).split(';'):
            if ':' not in entry:
                continue
            _, value_part = entry.split(':', 1)
            try:
                numeric_value = float(value_part.strip())
            except ValueError:
                continue
            max_val = max(max_val, numeric_value)
            found_numeric = True

        return max_val if found_numeric else np.nan

    def _extract_microbiome_presence_series(self, journey_data):
        """
        Return (series, status) where status indicates why data may be missing.
        status values: 'missing_column', 'parsed', or 'empty'.
        """
        if 'presence_microbiome' not in journey_data.columns:
            empty_series = pd.Series([np.nan] * len(journey_data), index=journey_data.index, dtype=float)
            return empty_series, 'missing_column'

        primary_bacteria = journey_data['primary_bacteria'].iloc[0]
        values = []
        any_value_recorded = False

        for cell in journey_data['presence_microbiome']:
            presence_value = np.nan
            if isinstance(cell, str) and cell.strip():
                entries = cell.split(';')
                keyed_entries = [entry for entry in entries if ':' in entry]

                if keyed_entries:
                    for entry in keyed_entries:
                        name_part, value_part = entry.split(':', 1)
                        if name_part.strip() == primary_bacteria:
                            presence_value = 1.0 if value_part.strip().lower() in ('true', '1') else 0.0
                            any_value_recorded = True
                            break
                elif len(entries) == 1:
                    token = entries[0].strip().lower()
                    if token in ('true', 'false', '1', '0'):
                        presence_value = 1.0 if token in ('true', '1') else 0.0
                        any_value_recorded = True

            values.append(presence_value)

        status = 'parsed' if any_value_recorded else 'empty'
        return pd.Series(values, index=journey_data.index, dtype=float), status
    
    def _determine_actual_resolution(self, journey_data):
        """Determine the actual resolution based on the data"""
        final_resolution = journey_data['resolution_type'].iloc[-1]
        
        # If resolution is NaN or empty, it's an ongoing journey
        if pd.isna(final_resolution) or final_resolution == '':
            return 'Ongoing'
        
        # Otherwise use the resolution from the data
        return final_resolution
    
